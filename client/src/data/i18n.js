// Fallback logic so any key missing in lesser-used languages falls back to Hindi / English gracefully
const DEFAULT_FALLBACK_ORDER = ["hi", "en"];

export function getTranslation(lang, key) {
  if (I18N[lang] && I18N[lang][key] !== undefined) {
    return I18N[lang][key];
  }
  for (const fb of DEFAULT_FALLBACK_ORDER) {
    if (I18N[fb] && I18N[fb][key] !== undefined) {
      return I18N[fb][key];
    }
  }
  return key;
}
